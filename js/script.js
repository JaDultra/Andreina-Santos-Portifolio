function setupSceneJourney() {
    const about = document.getElementById('about');
    const projects = document.getElementById('projects');
    const projectsBody = document.querySelector('.projects-body');
    if (!about || !projects || !projectsBody) return;
    let scheduled = false;
    const clamp = value => Math.max(0, Math.min(1, value));
    const ease = value => {
        const t = clamp(value);
        return t * t * (3 - 2 * t);
    };
    const update = () => {
        const viewport = window.innerHeight;
        const progressAt = element => ease((viewport * .78 - element.getBoundingClientRect().top) / (viewport * .66));
        const kitchen = progressAt(about);
        const plan = progressAt(projects);
        document.body.style.setProperty('--kitchen-progress', kitchen.toFixed(3));
        document.body.style.setProperty('--plan-progress', plan.toFixed(3));
        const overGrid = projectsBody.getBoundingClientRect().top <= 55;
        document.body.classList.toggle('header-on-plan', plan > .7 && !overGrid);
        document.body.classList.toggle('header-over-content', overGrid);
        document.body.classList.toggle('header-scrolled', window.scrollY > 12);
        scheduled = false;
    };
    window.addEventListener('scroll', () => {
        if (!scheduled) {
            requestAnimationFrame(update);
            scheduled = true;
        }
    }, { passive: true });
    window.addEventListener('resize', update);
    update();
}

function setupRevealSections() {
    const elements = document.querySelectorAll(".section-reveal");
    if (!elements.length) return;
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add("visible");
            }
        });
    }, { threshold: 0.15 });
    elements.forEach(el => observer.observe(el));
}

function setupLightbox() {
    const wrappers = document.querySelectorAll(".img-wrapper");
    const lightbox = document.getElementById("lightbox");
    const lightboxImg = document.getElementById("lightbox-img");
    const counter = document.getElementById("lightbox-counter");
    const closeBtn = document.querySelector(".lightbox .close");
    const prevBtn = document.querySelector(".lightbox .prev");
    const nextBtn = document.querySelector(".lightbox .next");
    if (!wrappers.length || !lightbox || !lightboxImg || !closeBtn || !prevBtn || !nextBtn || !counter) return;
    const images = Array.from(wrappers).map(wrapper => wrapper.querySelector("img").src);
    let currentIndex = 0;

    function updateCounter() {
        counter.textContent = `${currentIndex + 1} / ${images.length}`;
    }

    function updateNavigation() {
        prevBtn.classList.toggle("disabled", currentIndex === 0);
        nextBtn.classList.toggle("disabled", currentIndex === images.length - 1);
    }

    function showImage(index) {
        currentIndex = index;
        lightboxImg.src = images[currentIndex];
        updateCounter();
        updateNavigation();
        lightbox.style.display = "block";
    }
    wrappers.forEach((wrapper, index) => {
        wrapper.addEventListener("click", () => showImage(index));
    });
    closeBtn.addEventListener("click", () => {
        lightbox.style.display = "none";
    });
    prevBtn.addEventListener("click", () => {
        if (currentIndex > 0) {
            currentIndex--;
            lightboxImg.src = images[currentIndex];
            updateCounter();
            updateNavigation();
        }
    });
    nextBtn.addEventListener("click", () => {
        if (currentIndex < images.length - 1) {
            currentIndex++;
            lightboxImg.src = images[currentIndex];
            updateCounter();
            updateNavigation();
        }
    });
    lightbox.addEventListener("click", (event) => {
        if (event.target === lightbox) {
            lightbox.style.display = "none";
        }
    });
}

